import * as assert from "assert";
import { Readable } from "node:stream";
import {
  type ContentStorage,
  ContentNotFoundError,
  ContentExistsError,
  toBuffer
} from "./content.js";
import { streamToBuffer } from "./stream.js";

/**
 * Creates a stream generating a given number of bytes in chunks
 * @param sizeInBytes - total size in bytes
 * @param chunkSize - size per chunk
 * @returns Readable stream
 */
export function createByteStream(sizeInBytes: number, chunkSize: number = 64 * 1024): Readable {
  return Readable.from(
    (async function* generateBytes() {
      let remaining = sizeInBytes;
      let counter = 0;
      while (remaining > 0) {
        const currentChunk = Math.min(remaining, chunkSize);
        const buf = Buffer.alloc(currentChunk);
        for (let i = 0; i < currentChunk; i++) {
          buf[i] = (counter + i) % 256;
        }
        counter = (counter + currentChunk) % 256;
        remaining -= currentChunk;
        yield buf;
      }
    })()
  );
}

/**
 * Shared contract test suite for any ContentStorage implementation
 * @param factory - factory returning storage, a base URL prefix, and optional cleanup
 * @returns Contract test runner factory
 */
export function ContentStorageContract(factory: () => Promise<{
  storage: ContentStorage;
  baseUrl: string;
  isCloud?: boolean;
  cleanup?: () => Promise<void>;
}>) {
  return () => {
    let storage: ContentStorage;
    let baseUrl: string;
    let cleanupFn: (() => Promise<void>) | undefined;

    /**
     * Setup before contract tests
     */
    async function setup() {
      const res = await factory();
      storage = res.storage;
      baseUrl = res.baseUrl.endsWith("/") ? res.baseUrl : `${res.baseUrl}/`;
      cleanupFn = res.cleanup;
    }

    /**
     * Teardown after contract tests
     */
    async function teardown() {
      if (cleanupFn) {
        await cleanupFn();
      }
    }

    return {
      setup,
      teardown,

      async roundTripBufferAndString() {
        // String test: stored as content, not read from disk
        const strUrl = `${baseUrl}string-test.txt`;
        const strContent = "Hello Webda Content Storage! Not a path: /tmp/nonexistent";
        const putStrRes = await storage.putContent(strUrl, strContent, {
          contentType: "text/plain",
          metadata: { author: "webda" }
        });
        assert.ok(putStrRes);
        assert.strictEqual(putStrRes.size, Buffer.byteLength(strContent));

        const getStr = await storage.getContent(strUrl);
        const readStrBuf = await streamToBuffer(getStr);
        assert.strictEqual(readStrBuf.toString("utf-8"), strContent);

        // Buffer test
        const bufUrl = `${baseUrl}buffer-test.bin`;
        const bufContent = Buffer.from([1, 2, 3, 4, 5, 42, 99]);
        await storage.putContent(bufUrl, bufContent);

        const getBuf = await storage.getContent(bufUrl);
        const readBuf = await streamToBuffer(getBuf);
        assert.deepStrictEqual(readBuf, bufContent);
      },

      async roundTripStreamWithoutLength() {
        // Stream test with no contentLength, > 5 MiB for multipart testing
        const size = 5 * 1024 * 1024 + 128 * 1024; // 5.125 MiB
        const streamUrl = `${baseUrl}stream-test-${Date.now()}.bin`;
        const inputStream = createByteStream(size);

        const putRes = await storage.putContent(streamUrl, inputStream);
        assert.ok(putRes);

        const getStream = await storage.getContent(streamUrl);
        let receivedBytes = 0;
        let counter = 0;
        let match = true;

        for await (const chunk of getStream) {
          const buf = Buffer.isBuffer(chunk) ? chunk : Buffer.from(chunk);
          for (let i = 0; i < buf.length; i++) {
            if (buf[i] !== (counter + i) % 256) {
              match = false;
              break;
            }
          }
          counter = (counter + buf.length) % 256;
          receivedBytes += buf.length;
        }

        assert.strictEqual(receivedBytes, size, `Received ${receivedBytes} bytes, expected ${size}`);
        assert.ok(match, "Received bytes did not match generated byte sequence");
      },

      async missingKeyThrowsNotFoundError() {
        const missingUrl = `${baseUrl}nonexistent-${Date.now()}.bin`;
        await assert.rejects(
          async () => {
            await storage.getContent(missingUrl);
          },
          (err: any) => {
            return (
              err instanceof ContentNotFoundError ||
              err?.code === "CONTENT_NOT_FOUND" ||
              err?.name === "ContentNotFoundError" ||
              err?.name === "NoSuchKey" ||
              err?.code === "NoSuchKey"
            );
          }
        );
      },

      async rangeReadReturnsExactBytes() {
        const rangeUrl = `${baseUrl}range-test.txt`;
        const content = "0123456789ABCDEFGHIJKLMNOPQRSTUVWXYZ";
        await storage.putContent(rangeUrl, content);

        const stream = await storage.getContent(rangeUrl, { range: { start: 10, end: 19 } });
        const buf = await streamToBuffer(stream);
        assert.strictEqual(buf.toString("utf-8"), "ABCDEFGHIJ");
      },

      async ifNotExistsRejectsExistingKey() {
        const url = `${baseUrl}exists-test.txt`;
        await storage.putContent(url, "initial");

        await assert.rejects(
          async () => {
            await storage.putContent(url, "overwrite", { ifNotExists: true });
          },
          (err: any) => {
            return (
              err instanceof ContentExistsError ||
              err?.code === "CONTENT_EXISTS" ||
              err?.name === "ContentExistsError" ||
              err?.name === "PreconditionFailed" ||
              err?.code === "PreconditionFailed"
            );
          }
        );
      },

      async metadataAndHeadContent() {
        if (!storage.headContent) return;
        const metaUrl = `${baseUrl}meta-test.json`;
        const content = JSON.stringify({ hello: "world" });
        await storage.putContent(metaUrl, content, {
          contentType: "application/json",
          metadata: { env: "test", version: "1" }
        });

        const head = await storage.headContent(metaUrl);
        assert.ok(head);
        assert.strictEqual(head.size, Buffer.byteLength(content));
        assert.strictEqual(head.contentType, "application/json");
        if (head.metadata) {
          assert.strictEqual(head.metadata.env, "test");
        }

        const missingHead = await storage.headContent(`${baseUrl}does-not-exist.json`);
        assert.strictEqual(missingHead, undefined);
      },

      async streamErrorDoesNotLeaveCorruptedFile() {
        const failUrl = `${baseUrl}fail-stream-test.bin`;
        let pushed = false;
        const failingStream = new Readable({
          read() {
            if (!pushed) {
              pushed = true;
              this.push(Buffer.from("some initial bytes"));
              process.nextTick(() => {
                this.destroy(new Error("Stream exploded mid-transfer"));
              });
            }
          }
        });

        await assert.rejects(
          async () => {
            await storage.putContent(failUrl, failingStream);
          },
          /Stream exploded mid-transfer/
        );

        if (storage.headContent) {
          const head = await storage.headContent(failUrl);
          assert.strictEqual(head, undefined, "Corrupted file/object should not exist after stream failure");
        }
      }
    };
  };
}
