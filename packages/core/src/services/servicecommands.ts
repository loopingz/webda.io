import type { CommandArgDefinition, CommandDefinition } from "@webda/compiler";
import type { Application } from "../application/application.js";
import type { AbstractService } from "./iservice.js";
import { useLog } from "@webda/workout";

/**
 * A service command target: which service provides the command and how.
 */
export interface ServiceCommandTarget {
  /** Service type name from webda.module.json (e.g., "Webda/HttpServer") */
  name: string;
  /** Method name to call on the service */
  method: string;
  /** Service type identifier */
  type: string;
  /**
   * Arguments declared by this provider's handler, in its parameter order.
   *
   * The handler is called with a positional list built from these names: each value is
   * taken by name from the parsed arguments, falling back to this provider's own default.
   * When absent (hand-built targets), the merged {@link ServiceCommandInfo.args} are used.
   */
  args?: { [name: string]: CommandArgDefinition };
}

/**
 * Merged command info from one or more services declaring the same command.
 */
export interface ServiceCommandInfo {
  /** Human-readable description for CLI help */
  description: string;
  /** Services that handle this command (all execute in dependency order) */
  services: ServiceCommandTarget[];
  /**
   * Merged argument definitions from all services, used to build the CLI (yargs options, `--help`).
   *
   * The first definition of a name wins; its `default` is dropped when providers disagree on it, so each
   * handler falls back to its own default. Handlers receive their own arguments, see
   * {@link ServiceCommandTarget.args}.
   */
  args: { [name: string]: CommandArgDefinition };
  /** Merged capability requirements from all services declaring this command */
  requires: string[];
  /**
   * Lifecycle phase declared by each service providing this command, in the
   * same order as `services`. Values are one of:
   * - `"application"`: service declared phase "application", a static method called without Core.
   * - `"resolved"`: service declared phase "resolved" (e.g. via `@BuildCommand`).
   * - `"initialized"`: service declared phase "initialized".
   * - `undefined`: service did not declare a phase (treat as "initialized").
   *
   * The CLI dispatcher uses this to decide whether to skip `Core.init()`:
   * all-"application" → no Core; all-"resolved" → resolve-only; all-"initialized"/undefined → full init;
   * mixed → error.
   */
  phases: Array<"application" | "resolved" | "initialized" | undefined>;
}

/**
 * Collect all CLI commands declared by services across all loaded modules.
 *
 * Scans the `moddas`, `beans`, and `deployers` sections of `webda.module.json`
 * for services that have `commands` metadata (generated by the `@Command` decorator
 * at compile time). Merges commands from multiple services that declare the same
 * command name — each service becomes an entry in the `services` array, keeping its
 * own argument definitions, and args are merged into `args` for the CLI (first
 * definition wins for each arg name; a conflicting type is logged as a warning and
 * a disagreeing default is dropped from the merged definition).
 *
 * @param app - The loaded Webda Application with module metadata available
 * @returns A map of command names to their merged definitions
 *
 * @example
 * ```typescript
 * const commands = collectServiceCommands(app);
 * // {
 * //   "serve": {
 * //     description: "Start the HTTP server",
 * //     services: [{
 * //       name: "Webda/HttpServer", method: "serve", type: "Webda/HttpServer",
 * //       args: { port: { type: "number", default: 18080, alias: "p" } }
 * //     }],
 * //     args: { port: { type: "number", default: 18080, alias: "p" } }
 * //   }
 * // }
 * ```
 */
export function collectServiceCommands(app: Application): { [name: string]: ServiceCommandInfo } {
  const commands: { [name: string]: ServiceCommandInfo } = {};
  const modules = app.getModules();

  for (const section of ["moddas", "beans", "deployers"] as const) {
    for (const [typeName, metadata] of Object.entries(modules[section] || {})) {
      if (!metadata.commands) continue;
      for (const [cmdName, cmdDef] of Object.entries(metadata.commands)) {
        commands[cmdName] ??= {
          description: cmdDef.description,
          services: [],
          args: {},
          requires: [],
          phases: []
        };
        commands[cmdName].services.push({
          name: typeName,
          method: cmdDef.method,
          type: typeName,
          args: { ...cmdDef.args }
        });
        commands[cmdName].phases.push(cmdDef.phase);
        // Merge args from multiple services providing the same command, for the CLI
        mergeCommandArgs(cmdName, typeName, commands[cmdName].args, cmdDef.args || {});
        // Merge requires (union, no duplicates)
        for (const req of cmdDef.requires || []) {
          if (!commands[cmdName].requires.includes(req)) {
            commands[cmdName].requires.push(req);
          }
        }
      }
    }
  }

  return commands;
}

/**
 * Merge the arguments of one provider into the merged arguments of a command
 *
 * The first definition of a name wins. A different type is logged as a warning (the handler
 * declaring it still receives the value parsed with the first type); a different default is
 * removed from the merged definition, so the CLI leaves the value unset and each handler
 * falls back to its own default.
 *
 * @param cmdName - the command name, for logs
 * @param typeName - the provider type, for logs
 * @param merged - the merged arguments, updated in place
 * @param args - the arguments declared by the provider
 */
function mergeCommandArgs(
  cmdName: string,
  typeName: string,
  merged: { [name: string]: CommandArgDefinition },
  args: { [name: string]: CommandArgDefinition }
): void {
  for (const [argName, argDef] of Object.entries(args)) {
    const existing = merged[argName];
    if (!existing) {
      merged[argName] = { ...argDef };
      continue;
    }
    if (existing.type !== argDef.type) {
      useLog(
        "WARN",
        `Command '${cmdName}': argument '${argName}' of '${typeName}' is declared as ${argDef.type}, ` +
          `another provider declares it as ${existing.type}; the CLI parses it as ${existing.type}`
      );
    }
    if ("default" in existing && JSON.stringify(existing.default) !== JSON.stringify(argDef.default)) {
      delete existing.default;
    }
  }
}

/**
 * @param service - a service instance
 * @returns the names of its class and of every ancestor class
 */
function classChainNames(service: any): string[] {
  const names: string[] = [];
  for (let clazz = service?.constructor; clazz && clazz !== Function.prototype; clazz = Object.getPrototypeOf(clazz)) {
    if (clazz.name) names.push(clazz.name);
  }
  return names;
}

/**
 * Execute a CLI command by dispatching to all services that declared it.
 *
 * Every instance whose class (or an ancestor class) declares the command runs it once,
 * through the most-derived declaring type: a subclass redeclaring a command with `@Command`
 * replaces its parent's handler on its instances, a subclass that does not redeclare it
 * inherits the parent's. Providers run in declaration order. The `serviceFilter` filters to
 * specific services by type (supports suffix matching, an overridden ancestor type matches
 * too) or by instance name.
 *
 * Each service's command handler is called with its own declared arguments as
 * positional parameters, the values taken by name from `args` (falling back to
 * its own defaults). A handler returning a number sets the exit code: the
 * highest one wins, any other result counts as `0`.
 *
 * @param cmdName - The command name to execute (e.g., `"serve"`, `"migrate"`)
 * @param cmdInfo - The merged command definition from {@link collectServiceCommands}
 * @param args - Parsed argument values keyed by argument name
 * @param services - Map of service name to service instance (from Core.getServices())
 * @param serviceFilter - Optional list of service names to filter to (supports suffix matching)
 * @returns the highest exit code returned by the handlers (`0` on success), `1` if no services match the filter,
 *   a method is missing or no service instance ran
 *
 * @example
 * ```typescript
 * // Execute "migrate" on all services:
 * await executeServiceCommand("migrate", cmdInfo, { dryRun: true }, core.getServices());
 *
 * // Execute "migrate" on a specific service:
 * await executeServiceCommand("migrate", cmdInfo, { dryRun: true }, core.getServices(), ["PostgresMigrator"]);
 * ```
 */
export async function executeServiceCommand(
  cmdName: string,
  cmdInfo: ServiceCommandInfo,
  args: { [key: string]: any },
  services: { [key: string]: AbstractService },
  serviceFilter?: string[]
): Promise<number> {
  // Filter services if requested, by type (e.g. "HttpServer") or by instance name (e.g. a deployment unit)
  const filtered = serviceFilter && serviceFilter.length > 0;
  const typeMatches = (svc: ServiceCommandTarget) =>
    !filtered || serviceFilter.some(f => svc.name.endsWith(f) || svc.name === f);
  const instanceMatches = (service: AbstractService) =>
    filtered && typeof service.getName === "function" && serviceFilter.includes(service.getName());

  // Pick, for every instance, the provider running the command on it: a single target type can map to
  // multiple configured instances (e.g. two HttpServer services on different ports), and a subclass
  // inherits the command of its ancestors (e.g. an application `Authentication` running `auth migrate`).
  // When several providers of its class chain declare the command, the most-derived one replaces the
  // others: the command runs once per instance (a `RunnerHttpServer extends HttpServer` redeclaring
  // `serve` must not serve twice).
  const assignments = new Map<ServiceCommandTarget, AbstractService[]>(cmdInfo.services.map(svc => [svc, []]));
  // Providers with at least one instance of their class chain, to warn about the others
  const provided = new Set<ServiceCommandTarget>();
  let filterMatched = !filtered || cmdInfo.services.some(typeMatches);
  const instances = [...new Set(Object.values(services))].filter(instance => instance);
  for (const instance of instances) {
    const providers = cmdInfo.services
      .map(svc => ({ svc, rank: providerRank(instance, svc, services) }))
      .filter(({ rank }) => rank !== undefined);
    if (providers.length === 0) continue;
    providers.forEach(({ svc }) => provided.add(svc));
    // Run it when a filter names any of its providers (the overridden ones included) or the instance
    if (filtered && !providers.some(({ svc }) => typeMatches(svc)) && !instanceMatches(instance)) continue;
    filterMatched = true;
    // Most-derived provider first, the first declared one on a tie
    const best = providers.reduce((a, b) => (b.rank < a.rank ? b : a));
    assignments.get(best.svc).push(instance);
  }
  for (const svc of cmdInfo.services) {
    if (!provided.has(svc) && typeMatches(svc)) {
      useLog("WARN", `Service '${svc.name}' not found, skipping`);
    }
  }

  // Count executed handlers: a command where every provider was skipped did nothing
  let executed = 0;
  // Highest exit code returned by a handler
  let exitCode = 0;
  const recordExitCode = (result: any) => {
    if (typeof result === "number" && result > exitCode) {
      exitCode = result;
    }
  };
  // Long-running handlers (serve, worker) return a cancelable promise that stays
  // pending while they run: start them all, then wait for every one to settle.
  const running: PromiseLike<any>[] = [];
  // Execute in provider order, the instance registered under the provider name first
  for (const [svc, matches] of assignments) {
    matches.sort((a, b) => Number(b === services[svc.name]) - Number(a === services[svc.name]));
    // Each handler receives its own arguments, by name
    const commandArgs = handlerArguments(svc.args ?? cmdInfo.args, args);
    for (const service of matches) {
      if (!service[svc.method]) {
        const instanceName = typeof service.getName === "function" ? service.getName() : svc.name;
        useLog("ERROR", `Method '${svc.method}' not found on service '${instanceName}'`);
        return 1;
      }
      const result = service[svc.method](...commandArgs);
      if (isCancelable(result)) {
        running.push(result);
      } else {
        recordExitCode(await result);
      }
      executed++;
    }
  }

  if (!filterMatched) {
    useLog("ERROR", `No services match filter '${serviceFilter.join(",")}' for command '${cmdName}'`);
    return 1;
  }
  if (executed === 0) {
    useLog("ERROR", `No service instance found to run command '${cmdName}'`);
    return 1;
  }
  // Cancelling a long-running command (SIGINT, SIGTERM) is a clean stop
  await Promise.all(
    running.map(p =>
      Promise.resolve(p).then(recordExitCode, err => {
        if (err !== "Cancelled") {
          throw err;
        }
      })
    )
  );
  return exitCode;
}

/**
 * How closely a provider of a command matches an instance
 *
 * @param instance - the service instance (or class, for the `"application"` phase)
 * @param svc - the provider declaring the command
 * @param services - every instance by name
 * @returns the depth of the provider type in the instance class chain (`0` for its own class), a rank after
 *   every class for an instance registered under the provider name only, `undefined` when it does not apply
 */
function providerRank(
  instance: AbstractService,
  svc: ServiceCommandTarget,
  services: { [key: string]: AbstractService }
): number | undefined {
  const direct = services[svc.name] === instance;
  const depth = classChainNames(instance).indexOf(svc.type.split("/").pop());
  if (depth >= 0) {
    // Registered under the provider name breaks a tie between two types sharing a class name
    return depth * 2 + (direct ? 0 : 1);
  }
  return direct ? Number.MAX_SAFE_INTEGER : undefined;
}

/**
 * Build the positional arguments of a command handler
 *
 * An omitted argument falls back to the handler default, or keeps its slot as `undefined`
 * so the following ones stay in position.
 *
 * @param definitions - the arguments declared by the handler, in its parameter order
 * @param args - parsed argument values keyed by argument name
 * @returns the values to call the handler with
 */
function handlerArguments(definitions: { [name: string]: CommandArgDefinition }, args: { [key: string]: any }): any[] {
  return Object.keys(definitions).map(argName =>
    args[argName] !== undefined ? args[argName] : definitions[argName].default
  );
}

/**
 * Whether a command handler returned a long-running cancelable promise
 * (CancelablePromise or CancelableLoopPromise)
 *
 * @param result - the handler result
 * @returns true if the result can be cancelled
 */
function isCancelable(result: any): result is PromiseLike<any> & { cancel: () => Promise<void> } {
  return typeof result?.then === "function" && typeof result?.cancel === "function";
}
