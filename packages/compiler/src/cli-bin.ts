import { chmodSync, existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, normalize, posix, relative, resolve, sep } from "node:path";
import { useLog } from "@webda/workout";
import type { PackageDescriptor } from "./definition.js";

/**
 * Path of the executable generated for the `webda.cli` section, relative to the package root
 *
 * @param packageDescription - the package.json content
 * @returns `webda.cli.bin`, by default `bin/<name>.mjs`; undefined without `webda.cli`
 */
export function getCliBinPath(packageDescription: PackageDescriptor): string | undefined {
  const cli = packageDescription?.webda?.cli;
  if (!cli) {
    return undefined;
  }
  if (cli.bin) {
    return cli.bin;
  }
  // The unscoped package name when the CLI has no name
  const name = cli.name ?? packageDescription.name?.split("/").pop();
  return name ? `bin/${name}.mjs` : undefined;
}

/**
 * Content of the executable running the Webda CLI on the package
 *
 * @param binPath - path of the executable, relative to the package root
 * @returns the script
 */
export function generateCliBin(binPath: string): string {
  // From the executable folder back to the package root, as a URL relative to the script
  let root = relative(dirname(resolve("/", binPath)), resolve("/"))
    .split(sep)
    .join(posix.sep);
  root = root === "" ? "./" : `${root}/`;
  return `#!/usr/bin/env node
// Generated by webdac build from the "webda.cli" section of package.json: do not edit
import { fileURLToPath } from "node:url";
import { runCli } from "@webda/core/lib/bin/cli.js";
await runCli({ appPath: fileURLToPath(new URL(${JSON.stringify(root)}, import.meta.url)) });
`;
}

/**
 * Whether the package.json `bin` field references an executable
 *
 * @param packageDescription - the package.json content
 * @param binPath - path of the executable, relative to the package root
 * @returns true if `bin` (a string or a map) points to it
 */
function isDeclaredBin(packageDescription: PackageDescriptor, binPath: string): boolean {
  const bin = packageDescription.bin;
  const targets = typeof bin === "string" ? [bin] : Object.values(bin ?? {});
  return targets.some(target => typeof target === "string" && normalize(target) === normalize(binPath));
}

/**
 * Generate the executable of the `webda.cli` section of package.json
 *
 * The file is (re)written only when its content changes, with mode 755. A warning is logged
 * when the package.json `bin` field does not reference it: npm installs only the declared ones.
 *
 * @param appPath - the package root
 * @param packageDescription - the package.json content
 * @returns the absolute path of the executable and whether it was written; undefined without `webda.cli`
 */
export function writeCliBin(
  appPath: string,
  packageDescription: PackageDescriptor
): { path: string; written: boolean } | undefined {
  const binPath = getCliBinPath(packageDescription);
  if (!binPath) {
    return undefined;
  }
  const file = join(appPath, binPath);
  const content = generateCliBin(binPath);
  let written = false;
  if (!existsSync(file) || readFileSync(file, "utf-8") !== content) {
    mkdirSync(dirname(file), { recursive: true });
    writeFileSync(file, content);
    written = true;
    useLog("INFO", `Generated ${binPath}`);
  }
  chmodSync(file, 0o755);
  if (!isDeclaredBin(packageDescription, binPath)) {
    const name = packageDescription.webda?.cli?.name ?? packageDescription.name?.split("/").pop();
    useLog(
      "WARN",
      `package.json "bin" does not reference ${binPath}, generated from "webda.cli": add "bin": { "${name}": "${binPath}" }`
    );
  }
  return { path: file, written };
}
