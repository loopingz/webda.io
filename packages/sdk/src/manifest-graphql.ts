import { useApplication } from "@webda/core";
import type { ModelGraph } from "@webda/compiler";
import type {
  GraphQLExposure,
  GraphQLLink,
  GraphQLSelection,
  GraphQLSelectionField,
  OperationKind
} from "./client/types.js";
import type { SdkManifestModel, SdkManifestOperation } from "./manifest.js";

/**
 * The CRUD fields `GraphQLService.generateSchema()` gives a model (`GraphQLModelFields` of `@webda/graphql`)
 */
interface ModelFields {
  type: string;
  get: string;
  key: string;
  query: string;
  create?: string;
  update?: string;
  delete?: string;
}

/** Deepest nesting of plain objects described in a selection */
const MAX_DEPTH = 6;

/**
 * The `graphql-js` objects are read by duck typing: `@webda/graphql` (and `graphql`) is an optional peer dependency
 * @param type - a GraphQL type
 * @returns the named type under the List / NonNull wrappers
 */
function namedType(type: any): any {
  while (type?.ofType) type = type.ofType;
  return type;
}

/**
 * @param type - a named GraphQL type
 * @returns true for an output object type (one with fields and no input coercion)
 */
function isObjectType(type: any): boolean {
  return typeof type?.getFields === "function" && typeof type?.getInterfaces === "function";
}

/**
 * @param type - a named GraphQL type
 * @returns true for an input object type
 */
function isInputObjectType(type: any): boolean {
  return typeof type?.getFields === "function" && typeof type?.getInterfaces !== "function";
}

/**
 * How a relation attribute is sent by the REST API
 * @param relations - relations of the model holding the attribute
 * @param attribute - the attribute
 * @returns the reshaping of the GraphQL value
 */
function linkMode(relations: ModelGraph | undefined, attribute: string): GraphQLLink["as"] {
  const link = relations?.links?.find(l => l.attribute === attribute);
  if (link?.type === "LINKS_MAP") return "map";
  if (link?.type === "LINKS_ARRAY") return "ref";
  if (relations?.maps?.some(m => m.attribute === attribute)) return "ref";
  return "id";
}

/**
 * Describe the GraphQL exposure of the operations, from the schema the `GraphQLService` generated: the field each
 * operation is served by (the service records the placement of `graphqlPlacement()` and the CRUD field names of the
 * models), its arguments and the selection set of its result
 *
 * The selection keeps every field the server sends, except the related queries (`ModelRelated`), which the SDK reads
 * with their own query; a relation (parent, links, maps) selects the primary key of its target and is reshaped back
 * to what the REST API sends.
 * @param service - the configured `GraphQLService`
 * @param operations - the manifest operations, completed in place
 * @param models - the manifest models
 */
export function describeGraphQL(
  service: any,
  operations: Record<string, SdkManifestOperation>,
  models: Record<string, SdkManifestModel>
): void {
  const app = useApplication();
  if (!service.schema) {
    // Build hooks run at the `resolved` phase: the schema is generated by init(), generate it now
    service.app ??= app;
    service.generateSchema();
  }
  const schema = service.schema;
  if (!schema) return;
  const roots: Record<GraphQLExposure["kind"], Record<string, any>> = {
    query: schema.getQueryType?.()?.getFields() ?? {},
    mutation: schema.getMutationType?.()?.getFields() ?? {},
    subscription: schema.getSubscriptionType?.()?.getFields() ?? {}
  };
  const modelFields: Record<string, ModelFields> = service.modelFields ?? {};
  const placements: Record<string, { kind: GraphQLExposure["kind"]; name: string }> = service.operationPlacements ?? {};
  // GraphQL type name of a model to what a relation needs
  const modelTypes = new Map<string, { id: string; pk: string[]; separator?: string; relations?: ModelGraph }>();
  for (const [id, fields] of Object.entries(modelFields)) {
    const metadata: any = (app.getModels()[id] as any)?.Metadata;
    modelTypes.set(fields.type, {
      id,
      pk: models[id]?.primaryKey ?? (metadata?.PrimaryKey?.length ? [...metadata.PrimaryKey] : ["uuid"]),
      separator: models[id]?.primaryKeySeparator ?? metadata?.PrimaryKeySeparator,
      relations: models[id]?.relations ?? metadata?.Relations
    });
  }

  /**
   * @param type - an output type
   * @param depth - nesting
   * @returns its selection set, undefined for a scalar
   */
  const selectionOf = (type: any, depth: number = 0): GraphQLSelection | undefined => {
    const named = namedType(type);
    if (!isObjectType(named)) return undefined;
    const owner = modelTypes.get(named.name);
    const selection: GraphQLSelection = {};
    for (const field of Object.values(named.getFields()) as any[]) {
      const target = namedType(field.type);
      const key: string | undefined = field.extensions?.webdaKey;
      const attribute = key ?? field.name;
      if (!isObjectType(target)) {
        selection[field.name] = key ? { key } : 1;
        continue;
      }
      const related = modelTypes.get(target.name);
      if (owner && related) {
        // A relation of the model: its target's key, reshaped as the REST API sends it
        const link: GraphQLLink = {
          model: related.id,
          pk: related.pk,
          ...(related.separator ? { separator: related.separator } : {}),
          as: linkMode(owner.relations, attribute)
        };
        selection[field.name] = {
          ...(key ? { key } : {}),
          select: Object.fromEntries(related.pk.map(pk => [pk, 1])),
          link
        };
        continue;
      }
      // Related queries (`ModelRelated`) take arguments and are read through their own query
      if (owner && field.args?.length) continue;
      if (depth >= MAX_DEPTH) continue;
      const select = selectionOf(target, depth + 1);
      if (!select || !Object.keys(select).length) continue;
      const entry: GraphQLSelectionField = { select };
      if (key) entry.key = key;
      selection[field.name] = entry;
    }
    return selection;
  };

  /**
   * @param type - an input type
   * @returns its fields, GraphQL name to JSON key, undefined when it is not an input object
   */
  const inputFields = (type: any): Record<string, string> | undefined => {
    const named = namedType(type);
    if (!isInputObjectType(named)) return undefined;
    return Object.fromEntries(
      (Object.values(named.getFields()) as any[]).map(field => [field.name, field.extensions?.webdaKey ?? field.name])
    );
  };

  for (const op of Object.values(operations)) {
    const crud = op.model ? modelFields[op.model] : undefined;
    let placement: { kind: GraphQLExposure["kind"]; name: string } | undefined;
    const kind = op.kind as OperationKind | undefined;
    if (crud && kind && ["get", "query", "create", "update", "patch", "delete"].includes(kind)) {
      const name =
        kind === "get"
          ? crud.get
          : kind === "query"
            ? crud.query
            : kind === "create"
              ? crud.create
              : kind === "delete"
                ? crud.delete
                : // updateFromInput merges the attributes: it serves both PUT and PATCH
                  crud.update;
      if (name) placement = { kind: kind === "get" || kind === "query" ? "query" : "mutation", name };
    } else {
      placement = placements[op.id];
    }
    if (!placement) continue;
    const field = roots[placement.kind][placement.name];
    if (!field) continue;
    const exposure: GraphQLExposure = { kind: placement.kind, name: placement.name };
    const args: any[] = field.args ?? [];
    if (args.length) exposure.args = Object.fromEntries(args.map(arg => [arg.name, String(arg.type)]));
    if (crud && (kind === "create" || kind === "update" || kind === "patch")) {
      const arg = args.find(a => a.name === crud.type);
      if (arg) exposure.wrap = { arg: arg.name, fields: inputFields(arg.type) };
    } else if (args.length === 1 && args[0].name === "input") {
      // `operationArgs()` gives one `input` argument when the input properties cannot be arguments
      const ref = op.input.endsWith("?") ? op.input.slice(0, -1) : op.input;
      const properties = (app.getSchema(ref) as any)?.properties ?? {};
      if (!("input" in properties)) {
        const fields = inputFields(args[0].type);
        exposure.wrap = { arg: "input", ...(fields ? { fields } : {}) };
      }
    }
    const selection = selectionOf(field.type);
    if (selection) exposure.selection = selection;
    const resultModel = modelTypes.get(namedType(field.type)?.name ?? "");
    const listed = modelTypes.get(namedType(namedType(field.type)?.getFields?.()?.results?.type)?.name ?? "");
    const keys = (resultModel ?? listed)?.pk;
    if (keys) exposure.keys = keys;
    op.graphql = exposure;
  }
}
