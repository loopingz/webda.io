import { useService } from "@webda/core";
import { HttpServer } from "@webda/core/lib/services/httpserver.service.js";
import type { TestApplication } from "@webda/core/lib/test/objects.js";
import { GraphQLService } from "@webda/graphql";
import { suite, test } from "@webda/test";
import * as assert from "assert";
import { rmSync } from "node:fs";
import { join } from "node:path";
import { writeSdk } from "../test/compile.js";
import { SampleAppTest } from "../test/sample-app.js";
import { registerSdkFixture, SdkFixtureService } from "../test/sdk-fixture.js";
import { SdkError } from "./client/errors.js";
import { GraphQLTransport } from "./client/graphql/index.js";
import { HttpTransport } from "./client/http.js";
import { Link, SdkModel } from "./client/model.js";
import type { SdkGenerator } from "./sdkgenerator.service.js";

/**
 * The generated SDK, driven through the `GraphQLService` of `sample-app`: queries and mutations over HTTP,
 * subscriptions over graphql-ws, and the fallback to REST for an operation GraphQL does not expose
 */
@suite
class SdkGraphQLE2ETest extends SampleAppTest {
  static dir: string;
  static sdk: any;
  static baseUrl: string;
  static requests: string[] = [];
  static transports: GraphQLTransport[] = [];
  extraServices = {
    HttpServer: { type: "Webda/HttpServer", port: 0 },
    MainStore: {
      type: "Webda/MemoryStore",
      models: [
        "WebdaDemo/Company",
        "WebdaDemo/Project",
        "WebdaDemo/SubProject",
        "WebdaDemo/AnotherSubProject",
        "WebdaDemo/SubSubProject",
        "WebdaDemo/User"
      ]
    },
    SdkFixture: { type: "WebdaDemo/SdkFixtureService" },
    GraphQL: { type: "Webda/GraphQLService" }
  };

  /**
   * @param app - the test application
   */
  async tweakApp(app: TestApplication): Promise<void> {
    await super.tweakApp(app);
    app.addModda("WebdaDemo/SdkFixtureService", SdkFixtureService);
    app.addModda("Webda/HttpServer", HttpServer);
    app.addModda("Webda/GraphQLService", GraphQLService);
  }

  async beforeAll(): Promise<void> {
    await super.beforeAll();
    registerSdkFixture();
    // The schema was generated by init(): regenerate it with the fixture operations
    (useService("GraphQL" as any) as unknown as GraphQLService).generateSchema();
    const http: any = useService("HttpServer" as any);
    await http.start("127.0.0.1", 0);
    for (let i = 0; i < 100 && !http.server?.listening; i++) await new Promise(r => setTimeout(r, 10));
    SdkGraphQLE2ETest.baseUrl = `http://127.0.0.1:${http.server.address().port}`;
    SdkGraphQLE2ETest.dir = writeSdk(await useService<SdkGenerator>("SdkGenerator" as any).files());
    SdkGraphQLE2ETest.sdk = await import(join(SdkGraphQLE2ETest.dir, "index.ts"));
  }

  async afterAll(): Promise<void> {
    for (const transport of SdkGraphQLE2ETest.transports) await transport.close();
    if (SdkGraphQLE2ETest.dir) rmSync(SdkGraphQLE2ETest.dir, { recursive: true, force: true });
    await super.afterAll();
  }

  /**
   * @returns a fetch recording `METHOD path` and the GraphQL root field of each request
   */
  fetch(): typeof fetch {
    const requests = SdkGraphQLE2ETest.requests;
    return (url: any, init: any) => {
      const path = new URL(String(url)).pathname;
      const field = init?.body ? /\{\s*(\w+)/.exec(JSON.parse(init.body).query ?? "")?.[1] : undefined;
      requests.push(`${init?.method ?? "GET"} ${path}${field ? ` ${field}` : ""}`);
      return fetch(url, init);
    };
  }

  /**
   * @param rest - add the REST transport after GraphQL
   * @returns a client over GraphQL
   */
  client(rest: boolean = false) {
    SdkGraphQLE2ETest.requests.length = 0;
    const fetch = this.fetch();
    const graphql = new GraphQLTransport({ url: `${SdkGraphQLE2ETest.baseUrl}/graphql`, fetch });
    SdkGraphQLE2ETest.transports.push(graphql);
    return SdkGraphQLE2ETest.sdk.createClient({
      cache: { ttl: 60_000 },
      transports: rest ? [graphql, new HttpTransport({ baseUrl: SdkGraphQLE2ETest.baseUrl, fetch })] : [graphql]
    });
  }

  @test
  async crudWithCacheHitsAndInvalidation() {
    const api = this.client();
    const requests = SdkGraphQLE2ETest.requests;
    const events: any[] = [];
    api.Company.on("change", (event: any) => events.push(event));
    const created = await api.Company.create({ name: "Acme", permissions: ["PRODUCT_1"] });
    assert.ok(created instanceof SdkModel);
    assert.strictEqual(created.name, "Acme");
    assert.ok(created.uuid);
    // Cached by the create
    await Promise.all([api.Company.get(created.uuid), api.Company.get(created.uuid)]);
    assert.deepStrictEqual(requests, ["POST /graphql createCompany"]);
    const page = await api.Company.query(`name = 'Acme'`);
    assert.deepStrictEqual(
      page.results.map((c: any) => c.uuid),
      [created.uuid]
    );
    assert.ok(page.results[0] instanceof SdkModel);
    await api.Company.query(`name = 'Acme'`);
    assert.deepStrictEqual(requests, ["POST /graphql createCompany", "POST /graphql Companies"]);
    // Patch: updateCompany merges, the cache is merged and the queries invalidated
    const patched = await api.Company.patch(created.uuid, { name: "Acme Inc" });
    assert.strictEqual(patched.name, "Acme Inc");
    assert.deepStrictEqual(patched.permissions, ["PRODUCT_1"]);
    assert.strictEqual(requests.at(-1), "POST /graphql updateCompany");
    assert.strictEqual(api.cache.getQuery("WebdaDemo/Company", "name = 'Acme'"), undefined);
    assert.ok(events.some(event => event.type === "set" && event.uid === created.uuid));
    const reloaded = await api.Company.get(created.uuid, { cache: "reload" });
    assert.strictEqual(requests.at(-1), "POST /graphql Company");
    assert.strictEqual(reloaded.name, "Acme Inc");
    // @Shared method on an object read over GraphQL
    assert.strictEqual(reloaded.hasPermission("PRODUCT_1"), true);
    // Typed operation call over GraphQL
    assert.strictEqual((await api.call("Company.Get", { uuid: created.uuid })).name, "Acme Inc");
    await reloaded.delete();
    assert.strictEqual(requests.at(-1), "POST /graphql deleteCompany");
    assert.strictEqual(api.cache.getEntity("WebdaDemo/Company", created.uuid), undefined);
    const error: SdkError = await api.Company.get(created.uuid).catch((e: SdkError) => e);
    assert.ok(error instanceof SdkError, `${error}`);
    assert.strictEqual(error.status, 404);
    assert.strictEqual(error.code, "NOT_FOUND");
    assert.strictEqual(error.transport, "graphql");
  }

  @test
  async relationsAndProjections() {
    const api = this.client();
    const requests = SdkGraphQLE2ETest.requests;
    const company = await api.Company.create({ name: "Nested" });
    // The parent comes from the input: no path parameter over GraphQL
    const user = await api.User.create({ company: company.uuid, name: "Bob" });
    assert.strictEqual(requests.at(-1), "POST /graphql createUser");
    // The relation is selected as its target's key and comes back as the uid the REST API sends
    assert.ok(user.company instanceof Link);
    assert.strictEqual(String(user.company), company.uuid);
    let count = requests.length;
    assert.strictEqual((await user.company.get()).name, "Nested");
    assert.strictEqual(requests.length, count, "the company is served from the cache");
    // Projection: one round-trip for the user's name and its company's name
    const projected = await api.User.get(user.uuid, { select: ["name", "company.name"], cache: "reload" });
    const sent = requests.at(-1)!;
    assert.strictEqual(sent, "POST /graphql User");
    assert.strictEqual(projected.name, "Bob");
    assert.strictEqual(projected.email, undefined);
    assert.ok(projected.company instanceof Link);
    assert.strictEqual(String(projected.company), company.uuid);
    assert.strictEqual((projected.company as any).name, "Nested");
    // The projection refreshed the cached user without replacing it
    assert.strictEqual(api.cache.getEntity("WebdaDemo/User", user.uuid)?.data.name, "Bob");
    // A projected query page is not cached as a query
    count = requests.length;
    const page = await api.User.query(`name = 'Bob'`, { select: ["name"] });
    assert.deepStrictEqual(
      page.results.map((u: any) => [u.uuid, u.name, u.email]),
      [[user.uuid, "Bob", undefined]]
    );
    assert.strictEqual(requests.length, count + 1);
    assert.strictEqual(api.cache.getQuery("WebdaDemo/User", `name = 'Bob'`), undefined);
    await api.User.delete(user.uuid);
    await api.Company.delete(company.uuid);
  }

  @test
  async subscriptionsForServerStreams() {
    const api = this.client();
    const chunks: unknown[] = [];
    for await (const chunk of api.stream("SdkFixture.Ticks", { n: 3 })) chunks.push(chunk);
    assert.deepStrictEqual(chunks, [{ index: 1 }, { index: 2 }, { index: 3 }]);
    // No HTTP request: the subscription went over the WebSocket
    assert.deepStrictEqual(SdkGraphQLE2ETest.requests, []);
    // Breaking out of the loop ends the subscription
    const first: unknown[] = [];
    for await (const chunk of api.stream("SdkFixture.Ticks", { n: 100 })) {
      first.push(chunk);
      break;
    }
    assert.deepStrictEqual(first, [{ index: 1 }]);
  }

  @test
  async fallsBackToRestForOperationsGraphQLDoesNotExpose() {
    const api = this.client(true);
    const requests = SdkGraphQLE2ETest.requests;
    // `graphql: false`: no GraphQL exposure in the manifest, the REST transport carries it
    assert.strictEqual(api.operations["SdkFixture.Ping"].graphql, undefined);
    assert.deepStrictEqual(await api.call("SdkFixture.Ping", { text: "hi" }), { text: "HI" });
    assert.strictEqual(requests.length, 1);
    assert.ok(requests[0].startsWith("PUT /") || requests[0].startsWith("POST /"), requests[0]);
    assert.ok(!requests[0].includes("/graphql"), requests[0]);
    // The others still go over GraphQL
    const company = await api.Company.create({ name: "Fallback" });
    assert.strictEqual(requests.at(-1), "POST /graphql createCompany");
    await api.Company.delete(company.uuid);
    // GraphQL only: the operation is not exposed
    const graphqlOnly = this.client();
    const error: SdkError = await graphqlOnly.call("SdkFixture.Ping", { text: "hi" }).catch((e: SdkError) => e);
    assert.ok(error instanceof SdkError);
    assert.match(error.message, /not exposed on the configured transports \(graphql\)/);
  }
}
