/** Options of `generateSdk` */
export interface GenerateSdkOptions {
  /** Emit `models.ts` and the model clients @default true */
  models?: boolean;
  /** Emit a `package.json` for a workspace package */
  package?: { name: string; version?: string; sdkVersion?: string };
  /** `json-schema-to-typescript` options passthrough */
  types?: Partial<TypesOptions>;
  /** Module the generated code imports the runtime from @default "@webda/sdk/client" */
  clientModule?: string;
}

/** Names reserved by the generated files */
const RESERVED = ["Operations", "OperationId", "OPERATIONS", "MODELS", "SERVER", "Client", "createClient"];

/**
 * The names of the generated types and classes
 * @param manifest - the manifest
 * @param clientModule - runtime module
 * @returns the names
 */
export function generatorNames(manifest: SdkManifest, clientModule: string = "@webda/sdk/client"): GeneratorNames {
  // Models first: their classes take the short names, the schema types follow the same assignment
  const modelIds = Object.keys(manifest.models);
  const models = assignNames(modelIds, RESERVED);
  const types = new Map<string, string>();
  const schemaRefs = Object.keys(manifest.schemas).filter(ref => !modelIds.includes(ref));
  const others = assignNames(schemaRefs, [
    ...RESERVED,
    ...models.values(),
    ...[...models.values()].map(name => `${name}Client`)
  ]);
  for (const [ref, name] of models) types.set(ref, name);
  for (const [ref, name] of others) types.set(ref, name);
  return { types, models, clientModule };
}

/**
 * Generate `index.ts`: `createClient()` with a typed client and a property per model client
 * @param manifest - the manifest
 * @param names - the names
 * @param models - whether models are generated
 * @returns the file content
 */
export function generateIndex(manifest: SdkManifest, names: GeneratorNames, models: boolean): string {
  const lines: string[] = [];
  lines.push("/* eslint-disable */");
  lines.push("// Generated by @webda/sdk: do not edit");
  lines.push("");
  lines.push(`import { WebdaClient, type ClientOptions, type OfflineExtension } from ${quote(names.clientModule)};`);
  lines.push(`import { MODELS, OPERATIONS, SERVER, type Operations } from "./operations.js";`);
  const entries = models
    ? Object.values(manifest.models).map(model => ({ model, name: names.models.get(model.id)! }))
    : [];
  if (entries.length) {
    lines.push(`import { ${entries.map(({ name }) => `${name}Client`).join(", ")} } from "./models.js";`);
  }
  lines.push("");
  lines.push(`export type * as Types from "./types.js";`);
  lines.push(`export { MODELS, OPERATIONS, SERVER, type OperationId, type Operations } from "./operations.js";`);
  if (models) lines.push(`export * from "./models.js";`);
  lines.push(
    `export { SdkError, HttpTransport, EntityCache, MemoryCacheStorage, WebStorageCacheStorage } from ${quote(names.clientModule)};`
  );
  lines.push(`export type { ClientOptions, CallOptions, Transport, QueryResult } from ${quote(names.clientModule)};`);
  lines.push("");
  lines.push(`/** The client of the ${manifest.namespace} application */`);
  lines.push("export interface Client extends WebdaClient<Operations> {");
  for (const { model, name } of entries) {
    lines.push(`  /** ${model.id} */`);
    lines.push(`  readonly ${name}: ${name}Client;`);
  }
  lines.push("}");
  lines.push("");
  lines.push("/**");
  lines.push(" * Create the client");
  lines.push(" * @param options - base URL, headers, transports, cache policy, offline extension");
  lines.push(" * @returns the client, `offline` typed as the extension given");
  lines.push(" */");
  lines.push("export function createClient<O extends OfflineExtension | undefined = undefined>(");
  lines.push("  options: ClientOptions & { offline?: O } = {}");
  lines.push("): Client & { readonly offline: O } {");
  lines.push("  const client = new WebdaClient<Operations>({");
  lines.push("    ...options,");
  lines.push("    operations: OPERATIONS,");
  lines.push("    models: MODELS,");
  lines.push("    server: SERVER");
  lines.push("  });");
  if (entries.length) {
    lines.push("  const models = {");
    lines.push(entries.map(({ name }) => `    ${name}: new ${name}Client(client)`).join(",\n"));
    lines.push("  };");
    lines.push("  for (const model of Object.values(models)) client.registerModel(model);");
    lines.push("  return Object.assign(client, models) as Client & { readonly offline: O };");
  } else {
    lines.push("  return client as Client & { readonly offline: O };");
  }
  lines.push("}");
  lines.push("");
  return lines.join("\n");
}

/**
 * Generate the SDK files of a manifest
 * @param manifest - the manifest
 * @param options - generation options
 * @returns file name to content
 */
export async function generateSdk(
  manifest: SdkManifest,
  options: GenerateSdkOptions = {}
): Promise<Record<string, string>> {
  const names = generatorNames(manifest, options.clientModule);
  const models = options.models !== false;
  const files: Record<string, string> = {
    "types.ts": await generateTypes(manifest.schemas, names.types, options.types),
    "operations.ts": generateOperations(manifest, names),
    "index.ts": generateIndex(manifest, names, models),
    "manifest.json": JSON.stringify(manifest, null, 2)
  };
  if (models) files["models.ts"] = generateModels(manifest, names);
  if (options.package) {
    files["package.json"] = JSON.stringify(
      {
        name: options.package.name,
        version: options.package.version ?? "0.0.0",
        type: "module",
        main: "index.ts",
        types: "index.ts",
        dependencies: { "@webda/sdk": options.package.sdkVersion ?? "*" }
      },
      null,
      2
    );
  }
  return files;
}
