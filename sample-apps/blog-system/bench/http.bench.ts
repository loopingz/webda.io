import { suite, test } from "@webda/test";
import { resolve } from "node:path";
import * as grpc from "@grpc/grpc-js";
import * as protoLoader from "@grpc/proto-loader";
import { useService } from "@webda/core";
import { BenchmarkRunner, SeededRandom } from "@webda/bench";
import { appDir, BlogBench } from "./blog.js";
import { BLOG_DATASETS, seedBlog, type BlogDataset } from "./seed.js";

/**
 * Query of the feed, the same for both transports
 */
const FEED = "status = 'published' ORDER BY publishedAt DESC LIMIT 20";

/**
 * The same reads over REST, GraphQL and gRPC, through real servers on localhost (keep-alive HTTP/1.1 for REST and
 * GraphQL, one multiplexed h2c connection for gRPC): the difference with `blog.domain.*` is the cost of the network
 * layer, and between the transports the cost of each protocol
 */
@suite
class BlogHttpBench extends BlogBench {
  /**
   * Seeded data
   */
  data: BlogDataset;
  /**
   * Base URL of the server
   */
  baseUrl: string;
  /**
   * gRPC clients of the post services
   */
  grpc: { post: any; posts: any };

  /**
   * Keep an HTTP server and an h2c server for gRPC, on free ports, without TLS
   *
   * @param app - the application
   */
  async tweakApp(app: any) {
    await super.tweakApp(app);
    const services = app.getCurrentConfiguration().services;
    services.HttpServer = { type: "Webda/HttpServer", port: 0 };
    services.HttpServerH2c = { type: "Webda/HttpServer", port: 0, h2c: true };
    services.GRPCService = { type: "Webda/GrpcService" };
  }

  /**
   * Build the application, seed the blog and start listening
   */
  async beforeAll() {
    await super.beforeAll();
    const profile = new BenchmarkRunner({ suite: "blog", backend: this.backend, reporters: [] }).profile;
    await this.resetStore();
    this.data = await seedBlog(BLOG_DATASETS[profile.name] ?? BLOG_DATASETS.quick);
    const server: any = useService("HttpServer" as any);
    await server.start("127.0.0.1", 0);
    this.baseUrl = `http://127.0.0.1:${server.address().port}`;
    const h2c: any = useService("HttpServerH2c" as any);
    await h2c.start("127.0.0.1", 0);
    // The proto generated by `webdac build`, the one GRPCService serves
    const definition = protoLoader.loadSync(resolve(appDir, ".webda/app.proto"), {
      keepCase: true,
      longs: String,
      enums: String,
      defaults: true,
      oneofs: false
    });
    const pkg: any = grpc.loadPackageDefinition(definition).webda;
    const address = `127.0.0.1:${h2c.address().port}`;
    this.grpc = {
      post: new pkg.PostService(address, grpc.credentials.createInsecure()),
      posts: new pkg.PostsService(address, grpc.credentials.createInsecure())
    };
  }

  /**
   * Call a unary gRPC method
   *
   * @param client - the client
   * @param method - the method
   * @param request - the request message
   * @returns the response message
   */
  rpc(client: any, method: string, request: any): Promise<any> {
    return new Promise((resolve, reject) => {
      client[method](request, (err: Error, res: any) => (err ? reject(err) : resolve(res)));
    });
  }

  /**
   * Call the server
   *
   * @param method - HTTP method
   * @param path - path
   * @param body - JSON body
   * @returns the parsed body
   */
  async call(method: string, path: string, body?: any): Promise<any> {
    const res = await fetch(`${this.baseUrl}${path}`, {
      method,
      headers: body ? { "content-type": "application/json" } : {},
      body: body ? JSON.stringify(body) : undefined
    });
    const text = await res.text();
    if (res.status >= 400) {
      throw new Error(`${method} ${path} → ${res.status} ${text.substring(0, 200)}`);
    }
    const json = text ? JSON.parse(text) : undefined;
    if (json?.errors?.length) {
      throw new Error(`GraphQL error: ${JSON.stringify(json.errors).substring(0, 200)}`);
    }
    return json;
  }

  /**
   * Get a post and the feed, over REST and GraphQL
   */
  @test
  async transports() {
    const runner = new BenchmarkRunner({ suite: "blog", backend: this.backend });
    const rng = new SeededRandom(13);
    const slug = () => this.data.published[rng.int(this.data.published.length)];
    // Each read checks its answer: an empty or wrong response must not count as a fast success
    const getPost = async (fetchPost: (slug: string) => Promise<any>, extract: (res: any) => any) => {
      const expected = slug();
      const post = extract(await fetchPost(expected));
      if (post?.slug !== expected)
        throw new Error(`expected post ${expected}, got ${JSON.stringify(post)?.substring(0, 100)}`);
    };
    const feed = async (query: () => Promise<any>, extract: (res: any) => any[]) => {
      const results = extract(await query());
      if (!results?.length) throw new Error("empty feed");
    };
    const reads: [string, () => Promise<void>][] = [
      [
        "blog.http.rest.getPost",
        () =>
          getPost(
            s => this.call("GET", `/posts/${s}`),
            res => res
          )
      ],
      [
        "blog.http.grpc.getPost",
        () =>
          getPost(
            s => this.rpc(this.grpc.post, "Get", { slug: s }),
            res => res
          )
      ],
      [
        "blog.http.graphql.getPost",
        () =>
          getPost(
            s =>
              this.call("POST", "/graphql", {
                query: `{ Post(slug: "${s}") { slug title content status viewCount } }`
              }),
            res => res.data?.Post
          )
      ],
      [
        "blog.http.rest.feed",
        () =>
          feed(
            () => this.call("PUT", "/posts", { q: FEED }),
            res => res.results
          )
      ],
      [
        "blog.http.grpc.feed",
        () =>
          feed(
            () => this.rpc(this.grpc.posts, "Query", { query: FEED }),
            res => res.results
          )
      ],
      [
        "blog.http.graphql.feed",
        () =>
          feed(
            () =>
              this.call("POST", "/graphql", {
                query: `{ Posts(query: ${JSON.stringify(FEED)}) { results { slug title content status viewCount } } }`
              }),
            res => res.data?.Posts?.results
          )
      ]
    ];
    try {
      for (const concurrency of runner.profile.concurrency) {
        for (const [name, read] of reads) {
          await runner.closedLoop({
            name,
            params: { concurrency, posts: this.data.size.posts },
            concurrency,
            ops: Math.max(10, Math.floor(runner.profile.ops / 5)),
            op: async () => {
              await read();
            }
          });
        }
      }
    } finally {
      await runner.finish();
      this.grpc.post.close();
      this.grpc.posts.close();
      await (useService("HttpServer" as any) as any).stop();
      await (useService("HttpServerH2c" as any) as any).stop();
    }
  }
}
