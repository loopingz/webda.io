import { suite, test } from "@webda/test";
import * as assert from "assert";
import { mkdtempSync, readFileSync, rmSync, statSync, utimesSync, writeFileSync, mkdirSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { MemoryLogger, useWorkerOutput } from "@webda/workout";
import { generateCliBin, getCliBinPath, writeCliBin } from "./cli-bin.js";

/**
 * Run `fn` and return the warnings it logged
 * @param fn - the code to run
 * @returns the result and the warning lines
 */
function captureWarnings<T>(fn: () => T): { result: T; warnings: string[] } {
  const memoryLogger = new MemoryLogger(useWorkerOutput());
  let result: T;
  try {
    result = fn();
  } finally {
    memoryLogger.close();
  }
  return {
    result,
    warnings: memoryLogger
      .getLogs()
      .map(l => l.log)
      .filter(l => l?.level === "WARN")
      .map(l => l.args.join(" "))
  };
}

@suite
class CliBinTest {
  @test
  binPath() {
    assert.strictEqual(getCliBinPath({ name: "app", version: "1.0.0" } as any), undefined);
    assert.strictEqual(
      getCliBinPath({ name: "@loopingz/runner", webda: { cli: { name: "acp-runner" } } } as any),
      "bin/acp-runner.mjs"
    );
    assert.strictEqual(getCliBinPath({ name: "@loopingz/runner", webda: { cli: {} } } as any), "bin/runner.mjs");
    assert.strictEqual(getCliBinPath({ name: "app", webda: { cli: { name: "x", bin: "cli.mjs" } } } as any), "cli.mjs");
  }

  @test
  content() {
    assert.strictEqual(
      generateCliBin("bin/acp-loopingz-runner.mjs"),
      `#!/usr/bin/env node
// Generated by webdac build from the "webda.cli" section of package.json: do not edit
import { fileURLToPath } from "node:url";
import { runCli } from "@webda/core/lib/bin/cli.js";
await runCli({ appPath: fileURLToPath(new URL("../", import.meta.url)) });
`
    );
    assert.ok(generateCliBin("cli.mjs").includes('new URL("./", import.meta.url)'));
    assert.ok(generateCliBin("tools/bin/run.mjs").includes('new URL("../../", import.meta.url)'));
  }

  @test
  writesOnlyWhenChanged() {
    const dir = mkdtempSync(join(tmpdir(), "webda-cli-bin-"));
    try {
      const pkg: any = {
        name: "@loopingz/acp-loopingz-runner",
        bin: { "acp-loopingz-runner": "./bin/acp-loopingz-runner.mjs" },
        webda: { cli: { name: "acp-loopingz-runner", defaultCommand: "serve" } }
      };
      const { result, warnings } = captureWarnings(() => writeCliBin(dir, pkg));
      const file = join(dir, "bin", "acp-loopingz-runner.mjs");
      assert.deepStrictEqual(result, { path: file, written: true });
      assert.deepStrictEqual(warnings, []);
      assert.strictEqual(readFileSync(file, "utf-8"), generateCliBin("bin/acp-loopingz-runner.mjs"));
      if (process.platform !== "win32") {
        assert.strictEqual(statSync(file).mode & 0o777, 0o755);
      }

      // Unchanged: not rewritten
      const past = new Date(Date.now() - 3600_000);
      utimesSync(file, past, past);
      assert.deepStrictEqual(writeCliBin(dir, pkg), { path: file, written: false });
      assert.ok(Math.abs(statSync(file).mtimeMs - past.getTime()) < 2000);

      // Edited: rewritten
      writeFileSync(file, "// edited");
      assert.strictEqual(writeCliBin(dir, pkg).written, true);
      assert.strictEqual(readFileSync(file, "utf-8"), generateCliBin("bin/acp-loopingz-runner.mjs"));
    } finally {
      rmSync(dir, { recursive: true, force: true });
    }
  }

  @test
  warnsWhenPackageBinMissesIt() {
    const dir = mkdtempSync(join(tmpdir(), "webda-cli-bin-"));
    try {
      mkdirSync(join(dir, "bin"));
      const pkg: any = { name: "runner", bin: { other: "bin/other.mjs" }, webda: { cli: { name: "runner" } } };
      let { warnings } = captureWarnings(() => writeCliBin(dir, pkg));
      assert.strictEqual(warnings.length, 1);
      assert.ok(warnings[0].includes("bin/runner.mjs"), warnings[0]);
      // A string bin pointing to it is enough
      ({ warnings } = captureWarnings(() => writeCliBin(dir, { ...pkg, bin: "bin/runner.mjs" })));
      assert.deepStrictEqual(warnings, []);
      // No webda.cli: nothing generated
      assert.strictEqual(writeCliBin(dir, { name: "runner" } as any), undefined);
    } finally {
      rmSync(dir, { recursive: true, force: true });
    }
  }
}
