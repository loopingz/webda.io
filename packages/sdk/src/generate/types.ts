import type { JSONSchema7 } from "json-schema";
import { compile, type Options } from "json-schema-to-typescript";

/**
 * Rewrite a schema for `json-schema-to-typescript`: local `definitions` are dropped (they were hoisted into the
 * manifest), every `$ref` points into the flat `definitions` of the root schema by TypeScript name, unresolvable refs
 * become `unknown`
 * @param schema - a manifest schema
 * @param names - ref to TypeScript name
 * @returns the rewritten copy
 */
export function rewriteSchema(schema: JSONSchema7, names: Map<string, string>): JSONSchema7 {
  const visit = (node: any): any => {
    if (Array.isArray(node)) return node.map(visit);
    if (!node || typeof node !== "object") return node;
    if (typeof node.$ref === "string") {
      const raw = node.$ref.replace(/^#\/(definitions|components\/schemas)\//, "");
      let decoded = raw;
      try {
        decoded = decodeURIComponent(raw);
      } catch {
        // keep raw
      }
      const name = names.get(decoded) ?? names.get(raw);
      const { $ref, ...rest } = node;
      void $ref;
      if (!name) return { ...visit(rest), tsType: "unknown" };
      return { ...visit(rest), $ref: `#/definitions/${name}` };
    }
    const copy: any = {};
    for (const [key, value] of Object.entries(node)) {
      if (key === "definitions" || key === "$schema" || key === "$id") continue;
      // Keywords whose values are not schemas keep their content
      copy[key] = ["enum", "const", "default", "examples", "required"].includes(key) ? value : visit(value);
    }
    return copy;
  };
  return visit(schema);
}

/**
 * Generate `types.ts`: one exported interface or type per schema
 * @param schemas - the manifest schemas
 * @param names - ref to TypeScript name
 * @param options - `json-schema-to-typescript` options passthrough
 * @returns the file content
 */
export async function generateTypes(
  schemas: Record<string, JSONSchema7>,
  names: Map<string, string>,
  options: Partial<Options> = {}
): Promise<string> {
  const definitions: Record<string, JSONSchema7> = {};
  for (const [ref, schema] of Object.entries(schemas)) {
    const name = names.get(ref);
    if (!name) continue;
    definitions[name] = { ...rewriteSchema(schema, names), title: name };
  }
  const root: JSONSchema7 = {
    title: "WebdaSdkSchemas",
    type: "object",
    properties: {},
    additionalProperties: false,
    definitions
  };
  const compiled = await compile(root as any, "WebdaSdkSchemas", {
    bannerComment: "",
    declareExternallyReferenced: true,
    unreachableDefinitions: true,
    additionalProperties: false,
    strictIndexSignatures: false,
    format: false,
    ...options
  });
  // The root type carries nothing
  const body = compiled.replace(/export interface WebdaSdkSchemas \{\s*\}\s*/m, "");
  return `/* eslint-disable */\n// Generated by @webda/sdk from the application schemas: do not edit\n\n${body}`;
}
