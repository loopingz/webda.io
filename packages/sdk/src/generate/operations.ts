import type { SdkManifest, SdkManifestOperation } from "../manifest.js";
import { runtimeManifests } from "./descriptors.js";
import { docComment, quote } from "./naming.js";

/** What the generator knows about the names */
export interface GeneratorNames {
  /** Schema ref to TypeScript type name */
  types: Map<string, string>;
  /** Model id to generated class name */
  models: Map<string, string>;
  /** Module the runtime is imported from */
  clientModule: string;
}

/**
 * @param ref - schema ref, `void` or `<ref>?`
 * @param names - type names
 * @param fallback - type when the ref is unknown
 * @returns the TypeScript type
 */
export function typeOfRef(ref: string, names: GeneratorNames, fallback: string = "unknown"): string {
  if (!ref || ref === "void") return "void";
  const partial = ref.endsWith("?");
  const base = partial ? ref.slice(0, -1) : ref;
  const name = names.types.get(base);
  if (!name) return fallback;
  return partial ? `Partial<T.${name}>` : `T.${name}`;
}

/**
 * The input type of an operation: the model's input schema for create/update/patch, the action body joined to the
 * primary key for actions
 * @param manifest - the manifest
 * @param op - the operation
 * @param names - type names
 * @returns the TypeScript type
 */
export function inputType(manifest: SdkManifest, op: SdkManifestOperation, names: GeneratorNames): string {
  const model = op.model ? manifest.models[op.model] : undefined;
  if (model && (op.kind === "create" || op.kind === "update" || op.kind === "patch")) {
    const name = names.types.get(model.inputSchema);
    if (name) return op.kind === "create" ? `Partial<T.${name}>` : `Partial<T.${name}>`;
  }
  if (model && (op.kind === "action" || op.kind === "behavior")) {
    const body = actionBodyType(manifest, op, names);
    const base = typeOfRef(op.input, names, "{}");
    if (body && base !== "void" && base !== body) return `${base} & ${body}`;
    if (body) return body;
  }
  return typeOfRef(op.input, names);
}

/**
 * @param manifest - the manifest
 * @param op - an action or behavior operation
 * @param names - type names
 * @returns the type of the action body (`<Model>.<action>.input`), undefined when the action takes none
 */
export function actionBodyType(
  manifest: SdkManifest,
  op: SdkManifestOperation,
  names: GeneratorNames
): string | undefined {
  if (op.kind === "action" && op.action && op.model) {
    const ref = `${op.model}.${op.action.name}.input`;
    const name = names.types.get(ref);
    return name && manifest.schemas[ref] ? `T.${name}` : undefined;
  }
  return undefined;
}

/**
 * @param manifest - the manifest
 * @param op - the operation
 * @param names - type names
 * @returns the output type
 */
export function outputType(manifest: SdkManifest, op: SdkManifestOperation, names: GeneratorNames): string {
  const type = typeOfRef(op.output, names);
  if (type === "void" && op.streaming !== "none") return "unknown";
  if (type === "unknown" && op.output !== "void" && !manifest.schemas[op.output]) return "unknown";
  return type;
}

/**
 * Generate `operations.ts`: the `Operations` interface and the runtime manifests
 * @param manifest - the manifest
 * @param names - the names
 * @returns the file content
 */
export function generateOperations(manifest: SdkManifest, names: GeneratorNames): string {
  const lines: string[] = [];
  lines.push("/* eslint-disable */");
  lines.push("// Generated by @webda/sdk from the application operations: do not edit");
  lines.push("");
  lines.push(`import type { ModelsManifest, OperationsManifest } from ${quote(names.clientModule)};`);
  lines.push(`import type * as T from "./types.js";`);
  lines.push("");
  lines.push("/** Every operation of the application, typed by its schemas */");
  lines.push("export interface Operations {");
  for (const op of Object.values(manifest.operations)) {
    const doc = [op.summary, op.description, op.deprecated ? "@deprecated" : undefined].filter(Boolean).join("\n");
    lines.push(docComment(doc, "  ").trimEnd());
    lines.push(
      `  ${quote(op.id)}: { input: ${inputType(manifest, op, names)}; output: ${outputType(manifest, op, names)} };`
    );
  }
  lines.push("}");
  lines.push("");
  lines.push("/** Operation ids */");
  lines.push("export type OperationId = keyof Operations;");
  lines.push("");
  const runtime = runtimeManifests(manifest);
  lines.push("/** The operations, as the runtime needs them */");
  lines.push(`export const OPERATIONS: OperationsManifest = ${JSON.stringify(runtime.operations, null, 2)};`);
  lines.push("");
  lines.push("/** The models, as the runtime needs them */");
  lines.push(`export const MODELS: ModelsManifest = ${JSON.stringify(runtime.models, null, 2)};`);
  lines.push("");
  return lines.filter(line => line !== undefined).join("\n");
}
